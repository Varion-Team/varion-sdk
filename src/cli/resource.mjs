import path from 'node:path';
import { t } from '../i18n/index.mjs';
import { resourceConfig } from './config.mjs';
import { stringifyToml, tomlValue } from './toml.mjs';

export function resourceTomlText(project, { envName = null, parts = {} } = {}) {
  const { build } = project.config;
  const lines = [
    `# ${t('Generated by varion from varion.toml: edit varion.toml, not this file.')}`,
    'type = "js"',
    'main = "server/index.js"',
  ];
  const clientFiles = [];
  if (parts.client) {
    lines.push('client-type = "js"', 'client-main = "client/index.js"');
    clientFiles.push('client/**');
  }
  if (parts.ui) clientFiles.push('ui/**');
  clientFiles.push(...build.clientFiles);
  if (clientFiles.length) lines.push(`client-files = ${tomlValue(clientFiles)}`);
  if (build.loadscreen) lines.push(`loadscreen = ${tomlValue(build.loadscreen)}`);
  lines.push('enabled = true', `deps = ${tomlValue(build.deps)}`);
  const config = resourceConfig(project.config, { envName });
  let text = `${lines.join('\n')}\n`;
  if (Object.keys(config).length) text += `\n${stringifyToml({ config }).trimEnd()}\n`;
  return text;
}

export function resourceDirOf(project, serverDir) {
  return path.join(serverDir, 'resources', project.config.project.name);
}
