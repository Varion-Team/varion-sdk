import fs from 'node:fs';
import path from 'node:path';
import { t } from '../i18n/index.mjs';
import { mirrorDir } from '../shared/fs.mjs';
import { stringifyDotenv } from './config.mjs';
import { tomlKey, tomlLiteral, tomlString, tomlValue } from './toml.mjs';

// the server takes these as written, without escapes, so they go out as literal strings
const PATH_KEY = /(Dir|File)$/;

export function serverTomlText(
  settings,
  {
    resources,
    gamemode,
    header = t('Generated by varion from varion.toml: edit varion.toml, not this file.'),
  },
) {
  const { spawn: spawnAt, ...rest } = settings;
  const lines = header.split('\n').map((line) => `# ${line}`);
  for (const [key, value] of Object.entries(rest)) {
    if (value === undefined || value === null) continue;
    if (PATH_KEY.test(key) && typeof value === 'string')
      lines.push(`${tomlKey(key)} = ${tomlLiteral(value)}`);
    else lines.push(`${tomlKey(key)} = ${tomlValue(value)}`);
  }
  lines.push(`gamemode = ${tomlString(gamemode)}`, `resourcesDir = 'resources'`);
  if (!('modules' in rest)) lines.push('modules = []');
  if (Array.isArray(spawnAt) && spawnAt.length === 3) {
    lines.push(`spawnX = ${spawnAt[0]}`, `spawnY = ${spawnAt[1]}`, `spawnZ = ${spawnAt[2]}`);
  }
  lines.push('resources = [', ...resources.map((name) => `    ${tomlString(name)},`), ']');
  return `${lines.join('\n')}\n`;
}

export function listedResources(serverDir, lists) {
  const names = [];
  for (const list of lists) {
    const file = path.resolve(serverDir, list);
    if (!fs.existsSync(file)) continue;
    for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
      const name = line.trim();
      if (name && !name.startsWith('#')) names.push(name);
    }
  }
  return names;
}

export function syncExtraResources(project, serverDir) {
  const missing = [];
  for (const name of project.config.resources.extra) {
    const from = path.join(project.config.resources.dir, name);
    const to = path.join(serverDir, 'resources', name);
    if (fs.existsSync(path.join(from, 'resource.toml'))) mirrorDir(from, to);
    else if (!fs.existsSync(path.join(to, 'resource.toml'))) missing.push(name);
  }
  return missing;
}

export function writeServerFolder(
  serverDir,
  { settings, gamemode, assetResources = [], lists = [], extra = [], envValues = {} },
) {
  fs.mkdirSync(path.join(serverDir, 'resources'), { recursive: true });
  const ordered = [];
  for (const name of [
    ...assetResources,
    ...listedResources(serverDir, lists),
    ...extra,
    gamemode,
  ]) {
    if (!ordered.includes(name)) ordered.push(name);
  }
  fs.writeFileSync(
    path.join(serverDir, 'server.toml'),
    serverTomlText(settings, { resources: ordered, gamemode }),
    'utf8',
  );
  fs.writeFileSync(
    path.join(serverDir, '.env'),
    stringifyDotenv(envValues, {
      header: t("A copy of the project's .env for the game mode: edit .env in the project folder."),
    }),
    'utf8',
  );
  return ordered;
}
